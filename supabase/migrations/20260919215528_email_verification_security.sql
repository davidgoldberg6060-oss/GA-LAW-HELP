begin;

create table if not exists public.email_verification_tokens (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  token_hash varchar(64) not null unique,
  expires_at timestamp not null,
  used_at timestamp,
  created_at timestamp not null default (now() at time zone 'utc')
);

create index if not exists ix_email_verification_user_id on public.email_verification_tokens(user_id);
create index if not exists ix_email_verification_expires_at on public.email_verification_tokens(expires_at);

alter table public.email_verification_tokens enable row level security;
revoke all on table public.email_verification_tokens from anon, authenticated;
revoke all on sequence public.email_verification_tokens_id_seq from anon, authenticated;

commit;
