-- The mobile app never receives direct table or bucket privileges. The API owns
-- authorization and uses a protected server connection/service credential.
do $$ declare t text; begin
  foreach t in array array['users','cases','timeline_events','evidence','evidence_findings','upload_sessions',
    'analysis_jobs','legal_sources','legal_authorities','authority_versions','case_authority_links',
    'issue_analyses','audit_logs','refresh_tokens','password_reset_tokens'] loop
    execute format('alter table public.%I enable row level security',t);
    execute format('revoke all on table public.%I from anon, authenticated',t);
  end loop;
end $$;

commit;
