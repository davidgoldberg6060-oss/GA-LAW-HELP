begin;

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  email varchar(320) not null unique,
  password_hash varchar(255) not null,
  role varchar(20) not null default 'user' check (role in ('user','admin')),
  is_active boolean not null default true,
  verified_at timestamp null,
  created_at timestamp not null default (now() at time zone 'utc')
);

create table if not exists public.cases (
  id bigint generated by default as identity primary key,
  owner_id bigint not null references public.users(id) on delete cascade,
  title varchar(255) not null,
  case_number varchar(100), county varchar(100),
  case_type varchar(40) not null default 'criminal', stage varchar(80), narrative text,
  created_at timestamp not null default (now() at time zone 'utc'),
  updated_at timestamp not null default (now() at time zone 'utc')
);

create table if not exists public.timeline_events (
  id bigint generated by default as identity primary key,
  case_id bigint not null references public.cases(id) on delete cascade,
  occurred_at timestamp, event_type varchar(80) not null, title varchar(255) not null,
  details text, source_label varchar(40) not null default 'USER_REPORTED', source_ref varchar(255)
);

create table if not exists public.evidence (
  id bigint generated by default as identity primary key,
  case_id bigint not null references public.cases(id) on delete cascade,
  filename varchar(255) not null, media_type varchar(100) not null,
  sha256 varchar(64) not null check (sha256 ~ '^[0-9a-f]{64}$'),
  storage_key varchar(500) not null unique, size_bytes bigint not null default 0 check (size_bytes >= 0),
  original_preserved boolean not null default true,
  uploaded_at timestamp not null default (now() at time zone 'utc'), verified_at timestamp
);

create table if not exists public.evidence_findings (
  id bigint generated by default as identity primary key,
  evidence_id bigint not null references public.evidence(id) on delete cascade,
  start_ms integer, end_ms integer, finding_type varchar(60) not null,
  evidence_label varchar(30) not null, text text not null, confidence varchar(20), limitations text
);

create table if not exists public.upload_sessions (
  id varchar(36) primary key,
  case_id bigint not null references public.cases(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  filename varchar(255) not null, media_type varchar(100) not null default 'application/octet-stream',
  total_chunks integer not null check (total_chunks > 0), total_bytes bigint,
  status varchar(30) not null default 'UPLOADING', created_at timestamp not null default (now() at time zone 'utc')
);

create table if not exists public.analysis_jobs (
  id bigint generated by default as identity primary key,
  evidence_id bigint not null references public.evidence(id) on delete cascade,
  job_type varchar(50) not null, status varchar(30) not null default 'QUEUED',
  progress integer not null default 0 check (progress between 0 and 100), error text,
  created_at timestamp not null default (now() at time zone 'utc'),
  updated_at timestamp not null default (now() at time zone 'utc')
);

create table if not exists public.legal_sources (
  id bigint generated by default as identity primary key,
  name varchar(255) not null unique, jurisdiction varchar(100) not null default 'Georgia',
  base_url varchar(1000) not null, source_type varchar(60) not null,
  official boolean not null default false, enabled boolean not null default true
);

create table if not exists public.legal_authorities (
  id bigint generated by default as identity primary key,
  jurisdiction varchar(100) not null, authority_type varchar(50) not null,
  citation varchar(255) not null, title varchar(500), text text,
  effective_from date, effective_to date, status varchar(40) not null default 'UNVERIFIED',
  source_url varchar(1000), retrieved_at timestamp,
  unique (jurisdiction, citation)
);

create table if not exists public.authority_versions (
  id bigint generated by default as identity primary key,
  authority_id bigint not null references public.legal_authorities(id) on delete cascade,
  version_label varchar(255), text text not null, effective_from date, effective_to date,
  source_url varchar(1000) not null, content_sha256 varchar(64) not null,
  verification_status varchar(40) not null default 'UNVERIFIED',
  retrieved_at timestamp not null default (now() at time zone 'utc'),
  unique (authority_id, content_sha256)
);

create table if not exists public.case_authority_links (
  id bigint generated by default as identity primary key,
  case_id bigint not null references public.cases(id) on delete cascade,
  authority_id bigint not null references public.legal_authorities(id),
  authority_version_id bigint references public.authority_versions(id),
  proposition text not null, pinpoint text, source_location varchar(255),
  relevance varchar(30) not null default 'SUPPORTING', verified boolean not null default false
);

create table if not exists public.issue_analyses (
  id bigint generated by default as identity primary key,
  case_id bigint not null references public.cases(id) on delete cascade,
  issue varchar(255) not null, category varchar(80) not null, favors varchar(30) not null,
  analysis text not null, counterargument text, facts_needed text,
  confidence varchar(20) not null default 'NEEDS_REVIEW'
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  user_id bigint, action varchar(100) not null, object_type varchar(60) not null,
  object_id varchar(100), created_at timestamp not null default (now() at time zone 'utc')
);

create table if not exists public.refresh_tokens (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  token_hash varchar(64) not null unique, expires_at timestamp not null,
  revoked_at timestamp, replaced_by_hash varchar(64),
  created_at timestamp not null default (now() at time zone 'utc')
);

create table if not exists public.password_reset_tokens (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  token_hash varchar(64) not null unique, expires_at timestamp not null,
  used_at timestamp, created_at timestamp not null default (now() at time zone 'utc')
);

create index if not exists ix_cases_owner_id on public.cases(owner_id);
create index if not exists ix_timeline_case_id on public.timeline_events(case_id);
create index if not exists ix_evidence_case_id on public.evidence(case_id);
create index if not exists ix_evidence_sha256 on public.evidence(sha256);
create index if not exists ix_jobs_status_type on public.analysis_jobs(status, job_type);
create index if not exists ix_issue_case_id on public.issue_analyses(case_id);
create index if not exists ix_audit_user_created on public.audit_logs(user_id, created_at);
create index if not exists ix_refresh_user on public.refresh_tokens(user_id);

do $$ begin
