-- Privacy-safe first-party usage events and in-app feedback.
-- Additive and idempotent. These tables are also created on first use by
-- backend/app/usage_stats.py so the API can start before this file is applied.
-- No IP addresses, names, or question text are stored.

CREATE TABLE IF NOT EXISTS usage_events (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    occurred_at TIMESTAMP NOT NULL,
    event_type VARCHAR(32) NOT NULL,
    platform VARCHAR(16) NOT NULL,
    feature VARCHAR(32),
    device_hash VARCHAR(64),
    app_version VARCHAR(32)
);
CREATE INDEX IF NOT EXISTS ix_usage_events_day ON usage_events (occurred_at, event_type, platform);
CREATE INDEX IF NOT EXISTS ix_usage_events_hash ON usage_events (device_hash, occurred_at);

CREATE TABLE IF NOT EXISTS app_feedback (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    created_at TIMESTAMP NOT NULL,
    device_hash VARCHAR(64),
    platform VARCHAR(16) NOT NULL,
    app_version VARCHAR(32),
    screen VARCHAR(64),
    rating SMALLINT,
    category VARCHAR(16) NOT NULL,
    comment TEXT,
    contact_email VARCHAR(320)
);
CREATE INDEX IF NOT EXISTS ix_app_feedback_created ON app_feedback (created_at);
