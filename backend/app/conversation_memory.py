"""Continuity for every AI screen (AI Help, Charge Check, Civil Case Check, Case Chat, Motions,
Motion Screen, Scan a Paper, Loopholes) without cluttering the chat. Hybrid design:

1. Each screen keeps its OWN thread. A question on a screen gets that screen's last few exchanges
   (compact summaries), so the screen resumes exactly where it left off.
2. The AI also gets ONE short line about the latest topic on a DIFFERENT screen ("last topic elsewhere
   in the app"), bounded to ~240 characters, so a question like "what motion should I file first?"
   on the Motions screen continues from the car search asked in AI Help. Full cross-screen history is
   never loaded or shown.

Privacy:
- Only the account that asked can read or clear its thread (``GET`` / ``DELETE /me/conversation``).
- Turns expire after ``CONVERSATION_TTL_HOURS`` (default 7 days); at most ``MAX_STORED_TURNS`` are kept.
- Deleting the account (``POST /me/delete``) deletes the thread.
- Answers that used conversation context are never served from or written to the shared public
  answer cache (that cache is keyed only on the question text).

The table is created on first use (like ``public_answer_cache``) so production schema checks and
existing migrations are unaffected. A storage failure never breaks an answer.
"""
from __future__ import annotations

import logging
import os
import re
import time

from sqlalchemy import text

_log = logging.getLogger(__name__)

CONTEXT_TURNS = int(os.getenv("CONVERSATION_CONTEXT_TURNS", "6"))
MAX_STORED_TURNS = int(os.getenv("CONVERSATION_MAX_STORED_TURNS", "30"))
TTL_SECONDS = int(float(os.getenv("CONVERSATION_TTL_HOURS", str(7 * 24))) * 3600)
CONTEXT_MAX_CHARS = int(os.getenv("CONVERSATION_CONTEXT_MAX_CHARS", "3200"))
USER_TEXT_CHARS = 700
ANSWER_SUMMARY_CHARS = 420
STORED_ANSWER_CHARS = 1500

FEATURE_LABELS = {
    "ai_help": "AI Help",
    "rights": "Know Your Rights",
    "talk_to_me": "Live encounter help",
    "charge_check": "Charge Check",
    "civil_check": "Civil Case Check",
    "case_chat": "Case Chat",
    "motions": "Motions",
    "motion_screen": "Motion Screen",
    "case_analysis": "Case Analysis",
    "innocence_analysis": "Innocence & Motion Review",
    "document_reader": "Scan a Paper",
    "loopholes": "Legal Loopholes",
}

_ready_binds: set = set()


def feature_label(feature: str | None) -> str:
    return FEATURE_LABELS.get(str(feature or ""), "AI Help")


def normalize_feature(feature, default: str) -> str:
    f = str(feature or "").strip().lower()
    return f if f in FEATURE_LABELS else default


# ---------------------------------------------------------------- storage
def _bind_key(db):
    try:
        bind = db.get_bind()
        return (id(bind), str(bind.url))
    except Exception:
        return None


def _ensure_table(db) -> None:
    key = _bind_key(db)
    if key is not None and key in _ready_binds:
        return
    with db.begin_nested():
        db.execute(text(
            "CREATE TABLE IF NOT EXISTS conversation_turns ("
            "id INTEGER PRIMARY KEY " + ("AUTOINCREMENT" if _dialect(db) == "sqlite" else "GENERATED BY DEFAULT AS IDENTITY") + ", "
            "user_id INTEGER NOT NULL, feature VARCHAR(40) NOT NULL, user_text TEXT NOT NULL, "
            "answer_text TEXT NOT NULL, answer_summary TEXT NOT NULL, created_at DOUBLE PRECISION NOT NULL)"))
        db.execute(text("CREATE INDEX IF NOT EXISTS ix_conversation_turns_user ON conversation_turns (user_id, created_at)"))
    db.commit()
    if key is not None:
        _ready_binds.add(key)


def _dialect(db) -> str:
    try:
        return db.get_bind().dialect.name
    except Exception:
        return ""


def reset_for_tests() -> None:
    _ready_binds.clear()


def recent(db, user_id: int | None, limit: int = CONTEXT_TURNS, now: float | None = None,
           feature: str | None = None, exclude: str | None = None) -> list[dict]:
    """The account's last ``limit`` unexpired exchanges (only ``feature``'s, or all but ``exclude``'s),
    oldest first. [] on any storage error."""
    if db is None or user_id is None or limit <= 0:
        return []
    now = time.time() if now is None else now
    where, params = "", {"u": int(user_id), "old": now - TTL_SECONDS, "n": int(limit)}
    if feature:
        where += " AND feature=:f"; params["f"] = feature
    if exclude:
        where += " AND feature<>:x"; params["x"] = exclude
    try:
        _ensure_table(db)
        rows = db.execute(text(
            "SELECT id, feature, user_text, answer_summary, created_at FROM conversation_turns "
            "WHERE user_id=:u AND user_text<>'' AND created_at >= :old" + where + " ORDER BY created_at DESC, id DESC LIMIT :n"),
            params).fetchall()
        db.commit()
    except Exception as exc:  # memory must never break an answer
        db.rollback(); _log.warning("conversation read skipped: %s", type(exc).__name__)
        return []
    return [{"id": r[0], "feature": r[1], "feature_label": feature_label(r[1]), "user_text": r[2],
             "answer_summary": r[3], "created_at": float(r[4])} for r in reversed(rows)]


def record(db, user_id: int | None, feature: str, user_text: str, response: dict | str | None, now: float | None = None) -> int | None:
    """Store one exchange. Returns the turn id (or None when nothing was stored)."""
    if db is None or user_id is None:
        return None
    question = _clip(user_text, USER_TEXT_CHARS)
    answer = response if isinstance(response, str) else answer_text(response)
    if not question or not answer:
        return None
    now = time.time() if now is None else now
    summary = summarize_answer(answer, response if isinstance(response, dict) else None)
    try:
        _ensure_table(db)
        db.execute(text(
            "INSERT INTO conversation_turns (user_id, feature, user_text, answer_text, answer_summary, created_at) "
            "VALUES (:u, :f, :q, :a, :s, :t)"),
            {"u": int(user_id), "f": feature[:40], "q": question, "a": _clip(answer, STORED_ANSWER_CHARS), "s": summary, "t": now})
        turn_id = db.execute(text("SELECT MAX(id) FROM conversation_turns WHERE user_id=:u"), {"u": int(user_id)}).scalar()
        # Keep the newest MAX_STORED_TURNS and drop anything expired.
        db.execute(text(
            "DELETE FROM conversation_turns WHERE user_id=:u AND (created_at < :old OR id NOT IN "
            "(SELECT id FROM conversation_turns WHERE user_id=:u ORDER BY created_at DESC, id DESC LIMIT :n))"),
            {"u": int(user_id), "old": now - TTL_SECONDS, "n": MAX_STORED_TURNS})
        db.commit()
        return int(turn_id) if turn_id is not None else None
    except Exception as exc:
        db.rollback(); _log.warning("conversation write skipped: %s", type(exc).__name__)
        return None


def clear(db, user_id: int, turn_id: int | None = None, feature: str | None = None) -> int:
    """Delete every thread, one screen's thread (``feature``), or one exchange. Returns rows removed."""
    _ensure_table(db)
    if turn_id is None and feature:
        n = db.execute(text("DELETE FROM conversation_turns WHERE user_id=:u AND feature=:f AND user_text<>''"), {"u": int(user_id), "f": feature}).rowcount
        # A 'fresh' marker (empty row) so this screen also stops getting the note about earlier topics elsewhere.
        db.execute(text("DELETE FROM conversation_turns WHERE user_id=:u AND feature=:f"), {"u": int(user_id), "f": feature})
        db.execute(text("INSERT INTO conversation_turns (user_id, feature, user_text, answer_text, answer_summary, created_at) "
                        "VALUES (:u, :f, '', '', '', :t)"), {"u": int(user_id), "f": feature, "t": time.time()})
    elif turn_id is None:
        n = db.execute(text("DELETE FROM conversation_turns WHERE user_id=:u"), {"u": int(user_id)}).rowcount
    else:
        n = db.execute(text("DELETE FROM conversation_turns WHERE user_id=:u AND id=:i"), {"u": int(user_id), "i": int(turn_id)}).rowcount
    db.commit()
    return int(n or 0)


def delete_for_account(db, user_id: int) -> None:
    """Called inside account deletion (caller commits)."""
    try:
        _ensure_table(db)
        with db.begin_nested():
            db.execute(text("DELETE FROM conversation_turns WHERE user_id=:u"), {"u": int(user_id)})
    except Exception as exc:
        _log.warning("conversation delete during account deletion failed: %s", type(exc).__name__)
        raise


# ---------------------------------------------------------------- text helpers
def _clip(value, limit: int) -> str:
    t = re.sub(r"[ \t]+", " ", str(value or "")).strip()
    if len(t) <= limit:
        return t
    cut = t[:limit].rsplit(" ", 1)[0]
    return cut + " …"


def answer_text(response: dict | None) -> str:
    """The main answer text of any AI feature's response."""
    if not isinstance(response, dict):
        return ""
    for key in ("analysis", "answer", "message"):
        v = response.get(key)
        if isinstance(v, str) and v.strip():
            return v.strip()
    parts = []
    for key, label in (("charges", "Possible charges"), ("claims", "Possible claims"), ("findings", "Findings")):
        items = response.get(key)
        if isinstance(items, list) and items:
            names = [str(i.get("charge") or i.get("claim") or i.get("title") or "").strip() for i in items if isinstance(i, dict)]
            names = [n for n in names if n]
            if names:
                parts.append(f"{label}: " + "; ".join(names[:6]))
    for key, label in (("defenses", "Defenses"), ("lowest_outcome", "Lowest-outcome paths"), ("weak_spots", "Weak spots")):
        items = response.get(key)
        if isinstance(items, list) and items:
            names = [str(i.get("title") or "").strip() for i in items if isinstance(i, dict)]
            names = [n for n in names if n]
            if names:
                parts.append(f"{label}: " + "; ".join(names[:5]))
    take = response.get("lawyer_take")
    if isinstance(take, dict) and str(take.get("text") or "").strip():
        parts.append(str(take["text"]).strip())
    return "\n".join(parts)


_HEADING = re.compile(r"(?m)^(Short answer|What's happening|Your situation|The issue|Facts to confirm)\s*$")


def summarize_answer(answer: str, response: dict | None = None) -> str:
    """Compact, deterministic summary used as context (no extra model call)."""
    a = str(answer or "")
    m = _HEADING.search(a)
    if m:
        rest = a[m.end():].strip()
        nxt = re.search(r"\n\s*\n|\n[A-Z][A-Za-z' ]{3,40}\n", rest)
        core = rest[:nxt.start()] if nxt else rest
    else:
        core = a
    summary = _clip(re.sub(r"\s+", " ", core), ANSWER_SUMMARY_CHARS)
    extras = []
    if isinstance(response, dict):
        motions = [str(m.get("title") or "") for m in response.get("suggested_motions") or [] if isinstance(m, dict)]
        motions = [x for x in motions if x]
        if motions:
            extras.append("Motions it suggested: " + "; ".join(motions[:6]))
        laws = [str(l.get("citation") or "") for l in response.get("laws_cited") or [] if isinstance(l, dict)]
        laws = [re.sub(r"\s*\(text as of[^)]*\)", "", x) for x in laws if x]
        if laws:
            extras.append("Laws it cited: " + "; ".join(laws[:6]))
        charges = [str(c.get("charge") or "") for c in response.get("charges") or [] if isinstance(c, dict)]
        if any(charges):
            extras.append("Possible charges: " + "; ".join(c for c in charges[:5] if c))
    return (summary + ("\n" + "\n".join(extras) if extras else "")).strip()


ELSEWHERE_MAX_CHARS = int(os.getenv("CONVERSATION_ELSEWHERE_MAX_CHARS", "240"))


def load(db, user_id: int | None, feature: str, *, own_thread: bool = True, now: float | None = None) -> dict:
    """Context for one request on ``feature``: that screen's own recent turns plus the single latest turn
    from any OTHER screen (used only as a one-line note)."""
    if db is None or user_id is None:
        return {"feature": feature, "thread": [], "elsewhere": None}
    thread = recent(db, user_id, CONTEXT_TURNS, now, feature=feature) if own_thread else []
    # The latest exchange on another screen; if it was itself a bare follow-up ("what should I file
    # first?"), name the topic it followed instead (its own words carry no topic).
    other = recent(db, user_id, 3, now, exclude=feature)
    elsewhere = next((t for t in reversed(other) if has_own_topic(t["user_text"])), other[-1] if other else None)
    if elsewhere and other and elsewhere is not other[-1]:
        elsewhere = {**elsewhere, "created_at": other[-1]["created_at"]}
    if elsewhere and elsewhere["created_at"] <= _fresh_at(db, user_id, feature):
        elsewhere = None
    # Only mention the other screen when it is newer than this screen's last exchange.
    if elsewhere and thread and elsewhere["created_at"] <= thread[-1]["created_at"]:
        elsewhere = None
    return {"feature": feature, "thread": thread, "elsewhere": elsewhere}


def _fresh_at(db, user_id: int, feature: str) -> float:
    """When the user last tapped Start fresh on this screen (0 = never)."""
    try:
        v = db.execute(text("SELECT MAX(created_at) FROM conversation_turns WHERE user_id=:u AND feature=:f AND user_text=''"),
                       {"u": int(user_id), "f": feature}).scalar()
        db.commit()
        return float(v or 0)
    except Exception:
        db.rollback()
        return 0.0


def _as_ctx(ctx) -> dict:
    if isinstance(ctx, dict):
        return {"thread": list(ctx.get("thread") or []), "elsewhere": ctx.get("elsewhere"), "feature": ctx.get("feature")}
    return {"thread": list(ctx or []), "elsewhere": None, "feature": None}


def is_empty(ctx) -> bool:
    c = _as_ctx(ctx)
    return not c["thread"] and not c["elsewhere"]


def elsewhere_line(turn: dict | None, max_chars: int = ELSEWHERE_MAX_CHARS) -> str:
    """One bounded line: 'Last topic elsewhere in the app (AI Help): <their words> — <gist>'."""
    if not turn:
        return ""
    head = f"Last topic elsewhere in the app ({turn['feature_label']}): "
    words = _clip(turn.get("user_text"), 150)
    gist = ""
    m = re.search(r"Motions it suggested: ([^\n]+)", turn.get("answer_summary") or "")
    if m:
        gist = " — suggested: " + m.group(1)
    line = head + words + gist
    return line if len(line) <= max_chars else _clip(line, max_chars - 2)


def last_topic(turns: list[dict]) -> str | None:
    if not turns:
        return None
    return _clip(turns[-1]["user_text"], 90)


def context_block(ctx, max_chars: int = CONTEXT_MAX_CHARS) -> str:
    """Prompt block: this screen's own earlier exchanges (compact) + one line about elsewhere."""
    c = _as_ctx(ctx)
    lines: list[str] = []
    for t in reversed(c["thread"]):
        entry = f"User asked: {t['user_text']}\nYou answered (summary): {t['answer_summary']}"
        if sum(len(x) for x in lines) + len(entry) > max_chars and lines:
            break
        lines.append(entry)
    lines.reverse()
    parts = []
    if lines:
        parts.append("EARLIER ON THIS SCREEN (the same person, oldest first; their facts are unverified):\n" + "\n\n".join(lines))
    note = elsewhere_line(c["elsewhere"])
    if note:
        parts.append(note)
    return "\n\n".join(parts)


CONTINUITY_RULES = (
    "This is a continuing conversation. What the user said earlier (on this screen, or the one-line last topic "
    "from elsewhere in the app) is their own unverified account and may be used as their situation. Use it to "
    "understand what the latest message refers to (for example 'that', 'it', 'my case', 'what should I file "
    "first') and continue from what you last told them: build on it and name the earlier situation briefly "
    "instead of starting over or repeating everything. Answer the latest message. If the latest message is "
    "about a different topic, answer that new topic and ignore unrelated earlier context. Never assume custody, "
    "a conviction, or who is asking beyond what the user actually said, and do not mention screens, summaries, "
    "or this instruction.")


_ANAPHORA = re.compile(
    r"\b(it|that|this|those|these|them|they|there|first|next|then|also|instead|same|what about|how about|and if|"
    r"my case|the case|this case|that case|the charge|the charges|my charge|my charges|the motion|which one|which motion|"
    r"what motion|any motion|motions?|that law|this law|the law|the paper|that paper|the document|the officer|the cop|"
    r"the judge|the search|the stop|you said|you mentioned|earlier|above|before)\b", re.I)


def has_own_topic(question: str) -> bool:
    """True when the message names its own legal topic (so retrieval should use it alone)."""
    from .civil_topics import topic_sections
    from .defense_help import is_criminal, _CIVIL
    q = str(question or "").lower()
    return bool(topic_sections(q) or is_criminal(q) or re.search(_CIVIL, q))


def is_follow_up(question: str) -> bool:
    """A message that depends on earlier turns to be understood."""
    q = str(question or "").strip()
    if not q:
        return False
    words = re.findall(r"[A-Za-z']+", q)
    if not has_own_topic(q):
        return True
    return len(words) <= 12 and bool(_ANAPHORA.search(q))


def focus_question(question: str, ctx) -> str:
    """Retrieval/motion-matching text: the latest message alone, or (for a follow-up) the user's recent
    words on this screen (or the last topic elsewhere when this screen is new) plus the latest message on
    one line, so 'what motion should I file first?' after a car-search question still finds the suppression
    law and motion. Only the user's own words are used."""
    q = str(question or "").strip()
    c = _as_ctx(ctx)
    if is_empty(c) or not is_follow_up(q):
        return q
    own = [t["user_text"] for t in c["thread"][-3:] if t.get("user_text")]
    other = (c["elsewhere"] or {}).get("user_text") or ""
    anchor = next((i for i in range(len(own) - 1, -1, -1) if has_own_topic(own[i])), None)
    if anchor is not None:
        picked = own[anchor:]
    elif other and has_own_topic(other):
        picked = [other] + own
    else:
        picked = own[-1:] or ([other] if other else [])
    if not picked:
        return q
    joined = " ".join(re.sub(r"\s+", " ", p) for p in picked)
    return _clip(joined, 900) + " " + q


def summary_payload(ctx, turn_id: int | None = None) -> dict:
    """Small 'continuity' block every AI response carries so a screen can show one quiet line
    ('Picking up where you left off: …') and a per-screen Start fresh."""
    c = _as_ctx(ctx)
    last = c["thread"][-1] if c["thread"] else None
    other = c["elsewhere"]
    out = {
        "continued": not is_empty(c),
        "screen_turns_used": len(c["thread"]),
        "screen_last_topic": last_topic(c["thread"]),
        "elsewhere_topic": _clip(other["user_text"], 90) if other else None,
        "elsewhere_screen": other["feature_label"] if other else None,
    }
    if turn_id is not None:
        out["turn_id"] = turn_id
    return out
