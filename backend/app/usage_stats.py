    re.compile(r"^/public/rights-assistant/?$"),
    re.compile(r"^/public/ask/?$"),
    re.compile(r"^/charge-check/?$"),
    re.compile(r"^/civil-check/?$"),
    re.compile(r"^/loopholes/analyze/?$"),
    re.compile(r"^/documents/read/?$"),
    re.compile(r"^/documents/translate/?$"),
