TZ = ZoneInfo(os.getenv("STATS_TZ", "America/New_York"))
STATS_TOKEN_ENV = "STATS_ADMIN_TOKEN"
TOKEN_HEADER = "x-stats-token"

EVENT_TYPES = frozenset({"open", "session", "first_open", "install", "feature", "ai_question"})
PLATFORMS = frozenset({"web", "android"})
FEATURES = frozenset({
    "chat",
    "case_check",
    "motion_maker",
    "funny_laws",
    "find_legal_help",
    "uploads",
})
FEEDBACK_CATEGORIES = {
    "bug": "Bug or crash",
    "design": "Design or hard to use",
    "idea": "Missing feature or idea",
    "slow": "Slow",
    "other": "Other",
}
# POST paths that call the AI provider (same set as anonymous_access, kept local
# so this module does not depend on the answer pipeline).
