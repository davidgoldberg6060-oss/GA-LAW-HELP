"""Privacy-safe first-party usage counts and in-app feedback.

Stores only anonymous, hashed device ids, event names, platform, optional app
version, and (for feedback) a rating, category, comment and optional contact
email. Never stores IP addresses, names, or the text of legal questions.
Tables are created on first use so production can start before a migration is
applied, matching conversation_memory / public_answer_cache.
"""
